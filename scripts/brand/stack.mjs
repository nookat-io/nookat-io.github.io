// The Nookat mark: the app's three-layer blue stack with its slot, redrawn as
// vector from the app repo's icon (nookat-io/nookat public/logo.png).
// Measured on the app icon's 1024px canvas, then cropped to the stack and
// scaled to a 64-unit grid. <Glyph> in src/components/ui.tsx is generated from
// this file: `node stack.mjs` prints it.

// The app icon's blues; the top layer is also the site's --color-blue.
export const COLORS = {
  top: "#1494f2",
  middle: "#1c85db",
  bottom: "#1f6bb2",
  slot: "#ffffff",
  slotOpacity: 0.24,
};

const SLOPE = 0.455; // layer edges, about 24.5 degrees
const LEFT = 96;
const RIGHT = 929;
const CX = 512.5;
const RUN = CX - LEFT;

// The crop: a square around the stack with a small margin, mapped to 0..64.
const CROP = { x: 86, y: 92, size: 853 };
const K = 64 / CROP.size;
const map = ([x, y]) => [(x - CROP.x) * K, (y - CROP.y) * K];
const n = (v) => +v.toFixed(2);

function roundedPolygon(points, radii) {
  const unit = ([x, y]) => {
    const m = Math.hypot(x, y);
    return [x / m, y / m];
  };
  const corners = points.map((V, i) => {
    const P = points[(i - 1 + points.length) % points.length];
    const N = points[(i + 1) % points.length];
    const u1 = unit([P[0] - V[0], P[1] - V[1]]);
    const u2 = unit([N[0] - V[0], N[1] - V[1]]);
    const angle = Math.acos(u1[0] * u2[0] + u1[1] * u2[1]);
    const d = radii[i] / Math.tan(angle / 2);
    return {
      a: map([V[0] + u1[0] * d, V[1] + u1[1] * d]),
      b: map([V[0] + u2[0] * d, V[1] + u2[1] * d]),
      r: n(radii[i] * K),
      sweep: u1[0] * u2[1] - u1[1] * u2[0] < 0 ? 1 : 0,
    };
  });
  const pt = ([x, y]) => `${n(x)} ${n(y)}`;
  let d = `M${pt(corners.at(-1).b)}`;
  for (const c of corners)
    d += `L${pt(c.a)}A${c.r} ${c.r} 0 0 ${c.sweep} ${pt(c.b)}`;
  return d + "Z";
}

const TIP = 68;
const CY = 309.5;
const HW = CX - TIP;
const HH = HW * SLOPE;
const top = roundedPolygon(
  [
    [CX, CY - HH],
    [CX + HW, CY],
    [CX, CY + HH],
    [CX - HW, CY],
  ],
  [44, 20, 44, 20],
);

const THICKNESS = 145;
const layer = (y) =>
  roundedPolygon(
    [
      [LEFT, y],
      [CX, y + RUN * SLOPE],
      [RIGHT, y],
      [RIGHT, y + THICKNESS],
      [CX, y + RUN * SLOPE + THICKNESS],
      [LEFT, y + THICKNESS],
    ],
    [14, 30, 14, 12, 30, 12],
  );

// Centre line of the middle layer's right face.
const faceY = (x) => 387 + (RIGHT - x) * SLOPE + THICKNESS / 2;
const [sx1, sy1] = map([700, faceY(700)]);
const [sx2, sy2] = map([842, faceY(842)]);

export const MARK = {
  viewBox: "0 0 64 64",
  top,
  middle: layer(387),
  bottom: layer(596),
  slot: { x1: n(sx1), y1: n(sy1), x2: n(sx2), y2: n(sy2), width: n(34 * K) },
};

/** The mark's SVG body in the 64-unit grid. */
export function markBody(transform = "", c = COLORS) {
  const s = MARK.slot;
  return (
    `<g${transform ? ` transform="${transform}"` : ""}>` +
    `<path d="${MARK.bottom}" fill="${c.bottom}"/>` +
    `<path d="${MARK.middle}" fill="${c.middle}"/>` +
    `<path d="${MARK.top}" fill="${c.top}"/>` +
    `<line x1="${s.x1}" y1="${s.y1}" x2="${s.x2}" y2="${s.y2}" stroke="${c.slot}" stroke-opacity="${c.slotOpacity}" stroke-width="${s.width}" stroke-linecap="round"/>` +
    `</g>`
  );
}

/** The <Glyph> component for src/components/ui.tsx. */
export function glyphComponent(c = COLORS) {
  const s = MARK.slot;
  return `/** The Nookat mark. Generated by scripts/brand/stack.mjs; edit the geometry there. */
export function Glyph({ className }: { className?: string }) {
  return (
    <svg viewBox="${MARK.viewBox}" className={className} aria-hidden="true">
      <path fill="${c.bottom}" d="${MARK.bottom}" />
      <path fill="${c.middle}" d="${MARK.middle}" />
      <path fill="${c.top}" d="${MARK.top}" />
      <line x1="${s.x1}" y1="${s.y1}" x2="${s.x2}" y2="${s.y2}" stroke="${c.slot}" strokeOpacity="${c.slotOpacity}" strokeWidth="${s.width}" strokeLinecap="round" />
    </svg>
  );
}`;
}

